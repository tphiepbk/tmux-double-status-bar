#!/usr/bin/env bash

# 256 color definitions
COLOR_LIGHT_CYAN3="color159"
COLOR_DARK_MAGENTA="color91"
COLOR_GREEN4="color22"
COLOR_GREY93="color255"
COLOR_DARK_ORANGE3="color166"
COLOR_RED3="color160"
COLOR_DEEP_PINK4="color89"
