COLOR_WHITE="#FFFFFF"
COLOR_SALMON="#BF4440"
COLOR_BRIGHT_YELLOW="#FFED29"

# Window status
COLOR_WINDOW_ACTIVE_TEXT="#[fg=${COLOR_BRIGHT_YELLOW},bg=${COLOR_GREEN4}]"
COLOR_WINDOW_ACTIVE_SEP="#[fg=${COLOR_GREEN4},bg=${COLOR_DARK_RED}]"

# Left status bar: tmux version
COLOR_TMUX_VERSION_TEXT="#[fg=${COLOR_LIGHT_CYAN3},bg=${COLOR_DARK_MAGENTA}]"
COLOR_TMUX_VERSION_SEP="#[fg=${COLOR_DARK_MAGENTA},bg=${COLOR_DARK_RED}]"

# Left status bar: hostname
COLOR_HOSTNAME_TEXT="#[fg=${COLOR_WHITE},bg=${COLOR_DARK_ORANGE3}]"
COLOR_HOSTNAME_SEP="#[fg=${COLOR_DARK_ORANGE3},bg=${COLOR_DARK_RED}]"

# Left status bar: session name
COLOR_SESSION_TEXT="#[fg=${COLOR_BRIGHT_YELLOW},bg=${COLOR_RED3}]"
COLOR_SESSION_SEP="#[fg=${COLOR_RED3},bg=${COLOR_DARK_RED}]"

# Right status bar: CPU
# COLOR_CPU_TEXT="#[fg=${COLOR_WHITE},bg=${COLOR_SALMON}]"
COLOR_CPU_TEXT="#[fg=${COLOR_BRIGHT_YELLOW},bg=${COLOR_SALMON}]"
COLOR_CPU_SEP="#[fg=${COLOR_SALMON},bg=${COLOR_DARK_RED}]"

